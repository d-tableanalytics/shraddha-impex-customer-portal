/**
 * reset-transactions.js
 * -----------------------------------------------------------------------------
 * Clears all booking / indent / reservation activity for a fresh start.
 *
 * Deletes:
 *   reservations   — every booking, indent and reserve (all statuses)
 *   orders         — orders produced by confirmed bookings, incl. pendingQty indents
 *   notifications  — all reservation/order notifications
 *   auditlogs      — booking-related entries ONLY; "Update User" records are kept
 *
 * Resets:
 *   counters                — reservation/order/po sequences back to 0
 *   products_* bookedQuantity → 0
 *   products_* availableForSale → totalAvailableQuantity  (releases held stock)
 *
 * Physical stock (totalAvailableQuantity / openingStockQuantity) is NOT touched,
 * so the July counting figures stay exactly as loaded.
 *
 * Every affected collection is dumped to JSON before deletion.
 *
 * Usage:
 *   node scripts/reset-transactions.js            # dry run (default)
 *   node scripts/reset-transactions.js --apply    # backup, then delete
 */

import mongoose from 'mongoose';
import dotenv from 'dotenv';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.join(__dirname, '..', '.env') });

const APPLY = process.argv.includes('--apply');

// Audit entries generated by the booking lifecycle. Anything not listed here
// (currently "Update User") is administrative and is preserved.
const BOOKING_AUDIT_ACTIONS = [
  'Reservation Created',
  'Reservation Confirmed',
  'Reservation Updated',
  'Reservation Cancelled',
  'Reservation Expired',
  'Reminder Sent (Day 5)',
  'Final Reminder Sent',
];

const PRODUCT_COLLECTIONS = ['products_koken', 'products_bix', 'products_imada'];

const stamp = () => new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);

const run = async () => {
  console.log(`\n⚙️   Mode : ${APPLY ? 'APPLY (backs up, then DELETES)' : 'DRY RUN (no writes)'}\n`);

  await mongoose.connect(process.env.MONGODB_URI || process.env.MONGO_URI);
  const db = mongoose.connection.db;
  console.log(`🔌  Connected to MongoDB (${mongoose.connection.name})\n`);

  const auditFilter = { action: { $in: BOOKING_AUDIT_ACTIONS } };

  // ---------------------------------------------------------------------------
  // Survey
  // ---------------------------------------------------------------------------
  const plan = [
    { name: 'reservations',  filter: {} },
    { name: 'orders',        filter: {} },
    { name: 'notifications', filter: {} },
    { name: 'auditlogs',     filter: auditFilter },
  ];

  for (const p of plan) {
    p.matched = await db.collection(p.name).countDocuments(p.filter);
    p.total   = await db.collection(p.name).countDocuments();
  }

  const bookedStats = [];
  for (const c of PRODUCT_COLLECTIONS) {
    const n = await db.collection(c).countDocuments({ bookedQuantity: { $gt: 0 } });
    const agg = await db.collection(c).aggregate([
      { $group: { _id: null, booked: { $sum: '$bookedQuantity' } } },
    ]).toArray();
    bookedStats.push({ c, n, units: agg[0]?.booked ?? 0 });
  }

  const counters = await db.collection('counters').find({}).toArray();

  console.log('──────────── PLAN ────────────');
  plan.forEach(p =>
    console.log(`   delete ${String(p.matched).padStart(5)} / ${String(p.total).padEnd(5)} ${p.name}${p.name === 'auditlogs' ? `  (keeping ${p.total - p.matched} non-booking)` : ''}`)
  );
  console.log('   ---');
  bookedStats.forEach(b =>
    console.log(`   reset  ${String(b.n).padStart(5)} products in ${b.c} (${b.units} units held)`)
  );
  console.log('   ---');
  counters.forEach(c => console.log(`   reset  counter ${c._id}: ${c.seq} → 0`));
  console.log('──────────────────────────────\n');

  if (!APPLY) {
    console.log('🚫  Dry run — nothing written. Re-run with --apply to back up and delete.\n');
    await mongoose.disconnect();
    return;
  }

  // ---------------------------------------------------------------------------
  // Backup — written before a single document is removed
  // ---------------------------------------------------------------------------
  const backupDir = path.join(__dirname, '..', 'backups', `reset-${stamp()}`);
  fs.mkdirSync(backupDir, { recursive: true });
  console.log(`💾  Backing up to ${backupDir}`);

  for (const p of plan) {
    const docs = await db.collection(p.name).find(p.filter).toArray();
    fs.writeFileSync(path.join(backupDir, `${p.name}.json`), JSON.stringify(docs, null, 2));
    console.log(`     ${p.name}.json  (${docs.length} docs)`);
  }
  fs.writeFileSync(path.join(backupDir, 'counters.json'), JSON.stringify(counters, null, 2));
  console.log(`     counters.json  (${counters.length} docs)`);

  // Product booking state, enough to reconstruct if needed
  for (const c of PRODUCT_COLLECTIONS) {
    const docs = await db.collection(c)
      .find({ bookedQuantity: { $gt: 0 } })
      .project({ skuCode: 1, bookedQuantity: 1, availableForSale: 1, totalAvailableQuantity: 1 })
      .toArray();
    fs.writeFileSync(path.join(backupDir, `${c}.booked.json`), JSON.stringify(docs, null, 2));
    console.log(`     ${c}.booked.json  (${docs.length} docs)`);
  }
  console.log('');

  // ---------------------------------------------------------------------------
  // Delete
  // ---------------------------------------------------------------------------
  for (const p of plan) {
    const res = await db.collection(p.name).deleteMany(p.filter);
    console.log(`🗑️   ${p.name}: deleted ${res.deletedCount}`);
  }

  // ---------------------------------------------------------------------------
  // Release held stock — availableForSale returns to the full physical count
  // ---------------------------------------------------------------------------
  for (const c of PRODUCT_COLLECTIONS) {
    const res = await db.collection(c).updateMany(
      {},
      [{ $set: { bookedQuantity: 0, availableForSale: '$totalAvailableQuantity' } }]
    );
    console.log(`♻️   ${c}: released stock on ${res.modifiedCount} product(s)`);
  }

  // ---------------------------------------------------------------------------
  // Reset ID sequences
  // ---------------------------------------------------------------------------
  const cres = await db.collection('counters').updateMany({}, { $set: { seq: 0 } });
  console.log(`🔢  counters: reset ${cres.modifiedCount} sequence(s) to 0`);

  console.log('\n✅  Fresh start complete.\n');
  await mongoose.disconnect();
};

run().catch(async (err) => {
  console.error('\n❌  Failed:', err);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
